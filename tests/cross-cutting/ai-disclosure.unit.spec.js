const { test, expect } = require('@playwright/test');
const { translationOnly, liveAI, pageVerdict } = require('../../src/ai-disclosure.js');

// src/ai-disclosure.js reads a game's AI disclosure for the AI tab's two
// exclusions. Node unit — no browser. The texts are disclosures from real store
// pages (results.jsonl), the cases the rules were tuned on.

test.describe('AI disclosure — exclusions (unit)', () => {
    test('AI used only for translation keeps the game', () => {
        expect(translationOnly('Artificial intelligence was used for language translation in this game.')).toBe(true);
        expect(translationOnly('We used AI to create initial translations, which were then reviewed and refined by a human editor.')).toBe(true);
        expect(translationOnly('Only the translations of the game and the store page were made with the help of AI. '
            + "All art is drawn by the game's own code; no AI image generators were used.")).toBe(true);
        expect(translationOnly('All art, animation and characters in this game are hand-drawn. '
            + 'Some non-Chinese UI text and store descriptions were translated with the help of AI.')).toBe(true);
        expect(translationOnly('Generative AI (LLM) was used to translate the original Korean dialogue into English.')).toBe(true);
    });

    test('the game name in the text does not count as another use', () => {
        const text = "Artificial intelligence has been used in order to translate Race or Crash: Secret Racer League's page on Steam.";
        expect(translationOnly(text, 'Race or Crash: Secret Racer League')).toBe(true);
    });

    test('any other AI use next to translation does not keep the game', () => {
        expect(translationOnly('Meteors Are Art | Used for sound, translation, and some icons')).toBe(false);
        expect(translationOnly('Sound, Localization')).toBe(false);
        expect(translationOnly('Translation into other languages. Voice generation for teacher.')).toBe(false);
        expect(translationOnly('Help with translations and copywriting.')).toBe(false);
        expect(translationOnly('Assistance with interface prototyping; and assistance with localization.')).toBe(false);
        expect(translationOnly('AI translation with manual edited language localization； A few icon pictures；')).toBe(false);
    });

    test("the game's own text written with AI is another use", () => {
        expect(translationOnly('Texts and translations were created with the assistance of AI tools. '
            + 'Music, 3D models, game design and maps are not AI-generated.')).toBe(false);
        expect(translationOnly("Some of the game's text, including its translations and this store page, "
            + 'was written with the help of AI tools. Nothing is generated by AI while you play.')).toBe(false);
    });

    test('a negation keeps only what it denies', () => {
        // "we don't speak" is no statement of non-use, the quests are still a use.
        expect(translationOnly("This game uses AI language models to help refine certain quests with a tone that matches the "
            + "game's narrative universe and to provide accurate translations for languages we don't speak natively.")).toBe(false);
        // "don't affect gameplay" denies nothing about AI.
        expect(translationOnly("・A small number of 2D assets that don't affect gameplay (specifically poster and newspaper "
            + 'textures) were created using AI generation. ・Localization of English')).toBe(false);
    });

    test('a text with no translation in it is no translation-only game', () => {
        expect(translationOnly('Storytelling\n\nArtworks')).toBe(false);
        expect(translationOnly('')).toBe(false);
        expect(translationOnly(undefined)).toBe(false);
    });

    test('live AI during play is found, whatever else AI made', () => {
        // Whispers from the Star, the user's reference game.
        expect(liveAI('This game features fully voiced, AI-powered conversations and performances created in collaboration '
            + 'with an actor, with select visual elements created by our team with the help of AI tools.')).toBe(true);
        expect(liveAI('This game uses a local AI text generation model to power an npc.')).toBe(true);
        expect(liveAI('players can chat with in-game characters about the world, the characters and quests they are on.')).toBe(true);
        expect(liveAI('This game uses AI to generate dynamic NPC dialogue during gameplay.')).toBe(true);
        expect(liveAI('Table Night has an optional AI LLM game master: if the host turns it on with their own AI account, '
            + 'a language model narrates the match and judges what players write.')).toBe(true);
        expect(liveAI('During play, optional online features use Anthropic Claude to generate character dialogue and '
            + 'evaluate player-written responses in story challenges.')).toBe(true);
    });

    test('AI used only during development is no live AI', () => {
        expect(liveAI('Generative AI tools were used to assist with some of the game\'s artwork and translations. '
            + 'All content was directed, selected and edited by the developer. Nothing is generated while you play.')).toBe(false);
        expect(liveAI('This game uses some pre-rendered UI icons and promotional images created with generative AI tools. '
            + 'No AI is used during gameplay.')).toBe(false);
        expect(liveAI('Specifically, AI was used to generate the promotional library capsules on the store page, '
            + 'as well as the 2D icon graphics for the upgrade cards shown during gameplay.')).toBe(false);
        expect(liveAI('Chinese uses live voice acting, while other countries use AI generated voice acting.')).toBe(false);
        expect(liveAI("Everything you see and hear is generated procedurally by the game's own code at runtime.")).toBe(false);
        expect(liveAI('Generative AI (LLM) was used to translate the original Korean dialogue into English.')).toBe(false);
        expect(liveAI('Storytelling\n\nArtworks')).toBe(false);
        expect(liveAI(undefined)).toBe(false);
    });
});

test.describe('AI disclosure — the game of an open store page (unit)', () => {
    // 10 and 20 are listed, 20 is kept by a ticked box.
    const all = new Set([10, 20]);
    const left = new Set([10]);
    const keep = { translation: true, ingame: true };
    const page = (id, text, reads) => ({ id, all, left, text, nameOf: () => { reads.name += 1; return 'Race or Crash'; } });

    test('a listed game goes by the lists, its name unread', () => {
        const reads = { name: 0 };
        expect(pageVerdict(page(10, 'Art was made with AI.', reads), keep)).toEqual({ listed: true, name: '', ai: true });
        expect(pageVerdict(page(20, '', reads), keep)).toEqual({ listed: true, name: '', ai: false });
        expect(reads.name).toBe(0);
    });

    test('a game newer than the lists goes by its text, its name read only when there is one', () => {
        const reads = { name: 0 };
        expect(pageVerdict(page(99, '', reads), keep).ai).toBe(false);
        expect(reads.name).toBe(0);
        const tr = "Artificial intelligence has been used in order to translate Race or Crash's page on Steam.";
        expect(pageVerdict(page(99, tr, reads), keep)).toEqual({ listed: false, name: 'Race or Crash', ai: false });
        expect(pageVerdict(page(99, tr, reads), {}).ai).toBe(true);
        expect(reads.name).toBe(2);
    });
});
